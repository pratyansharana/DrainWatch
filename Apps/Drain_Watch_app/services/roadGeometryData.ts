export function getCorridorRoadCoordinates(nodes: string[]): LatLng[] {
  if (!nodes || nodes.length < 2) return [];

  const fullPath: LatLng[] = [];

  for (let i = 0; i < nodes.length - 1; i++) {
    const u = nodes[i];
    const v = nodes[i + 1];
    const forwardKey = `${u}->${v}`;
    const reverseKey = `${v}->${u}`;

    let segment = CORRIDOR_ROAD_SEGMENTS[forwardKey];
    if (segment) {
      // Avoid duplicating joint point
      if (fullPath.length > 0) {
        fullPath.push(...segment.slice(1));
      } else {
        fullPath.push(...segment);
      }
    } else if (CORRIDOR_ROAD_SEGMENTS[reverseKey]) {
      const rev = [...CORRIDOR_ROAD_SEGMENTS[reverseKey]].reverse();
      if (fullPath.length > 0) {
        fullPath.push(...rev.slice(1));
      } else {
        fullPath.push(...rev);
      }
    }
  }

  return fullPath;
}
